/**
 * Universal text translation function:
 * 1. Looks up direct string or trimmed string in the target language dictionary.
 * 2. If not an exact match, performs sub-phrase and keyword replacement.
 */
export const translateText = (text: string, lang: SupportedLanguage = "EN"): string => {
  if (lang === "EN" || !text) return text;
  const map = TRANSLATION_MAP[lang];
  if (!map) return text;

  // 1. Direct match
  if (map[text]) return map[text];

  // 2. Trimmed match
  const trimmed = text.trim();
  if (map[trimmed]) {
    const leading = text.match(/^\s*/)?.[0] || "";
    const trailing = text.match(/\s*$/)?.[0] || "";
    return leading + map[trimmed] + trailing;
  }

  // 3. Sub-phrase replacement for dynamic or composite sentences
  let replaced = text;
  let hasReplaced = false;

  for (const k of Object.keys(map)) {
    if (k.length >= 4 && replaced.includes(k)) {
      replaced = replaced.split(k).join(map[k]);
      hasReplaced = true;
    }
  }

  return hasReplaced ? replaced : text;
};
